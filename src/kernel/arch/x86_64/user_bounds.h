#ifndef BUZZOS_X86_64_USER_BOUNDS_H
#define BUZZOS_X86_64_USER_BOUNDS_H

#include <stdint.h>

/* Native x86_64 user layout.  No user pointer is intentionally constrained
 * below 4 GiB; syscall and GUI structures carry full-width addresses. */
#define USER_SPACE_START        UINT64_C(0x0000000100000000)
#define USER_LOAD_START         UINT64_C(0x0000000100000000)
#define USER_LOAD_END           UINT64_C(0x0000000200000000)

#define USER_DISPLAY_START      UINT64_C(0x0000000200000000)
#define USER_DISPLAY_SIZE       UINT64_C(0x0000000004000000) /* 64 MiB */

#define USER_SHM_START          UINT64_C(0x0000000210000000)
#define USER_SHM_SLOT_SIZE      UINT64_C(0x0000000004000000) /* 64 MiB */
#define USER_SHM_SLOTS          64u
#define USER_SHM_END            (USER_SHM_START + USER_SHM_SLOT_SIZE * USER_SHM_SLOTS)

#define USER_GPU_START          UINT64_C(0x0000000400000000)
#define USER_GPU_SLOT_SIZE      UINT64_C(0x0000000004000000)
#define USER_GPU_SLOTS          64u
#define USER_GPU_END            (USER_GPU_START + USER_GPU_SLOT_SIZE * USER_GPU_SLOTS)
#define USER_GPU_BUDGET_BYTES   UINT64_C(0x0000000020000000) /* 512 MiB */

#define USER_DEFAULT_STACK_TOP  UINT64_C(0x00007FFFFFF00000)
#define USER_MAIN_STACK_SIZE    UINT64_C(0x0000000000800000) /* 8 MiB */
#define USER_THREAD_STACK_SIZE  UINT64_C(0x0000000000100000) /* 1 MiB */
#define USER_THREAD_STACK_SLOTS 256u
#define USER_TRAMPOLINE_BASE    UINT64_C(0x00007FFFFFFFF000)

#define USER_SPACE_END          UINT64_C(0x0000800000000000)
#define USER_PTR_START          USER_SPACE_START
#define USER_PTR_END            USER_SPACE_END

#endif
